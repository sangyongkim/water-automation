"""
rainfall.py  (v2 - 홍수량 산정 표준지침 기반, 엑셀 계수 완전 반영)
======================================================================
환경부 홍수량 산정 표준지침(2019) 완전 준수.

처리 흐름:
  1. 관측소별 확률강우량 + 티센 가중치 → 유역 평균 확률강우량
  2. 면적우량환산계수(ARF) 적용 (유역면적 > 25.9 km², 본류 권역별)
  3. 군집지역별 수정 Huff 6차 다항식 → 누가강우비 배열
  4. HEC-1 PC 카드용 누가강우비 반환

지원 강우강도식:
  poly6, poly5, general, talbot, sherman, japanese

Huff 계수:
  엑셀 '강우시간분포_Huff_.xlsx' 4개 시트에서 추출 (26군집 × 4분위)
  각 시트는 해당 분위의 50% 누가곡선 계수를 수록
  F(t) = a·t^6 + b·t^5 + c·t^4 + d·t^3 + e·t^2 + f·t + g  (t: 0~100)
  반환값: 0~100(%) → 내부에서 0~1로 변환

ARF 권역:
  '한강', '낙동강', '금강', '영산강'
  유역 본류에 따라 config에서 지정
"""

import math
import warnings


# ============================================================
# 1. 강우강도식
# ============================================================

def calc_intensity(formula: str, params: dict, duration_min: float) -> float:
    if formula in ('poly5', 'poly6'):
        t_hr  = duration_min / 60.0
        log_t = math.log(t_hr)
        deg   = 5 if formula == 'poly5' else 6
        log_I = sum(params[f'a{i}'] * (log_t ** i) for i in range(deg + 1))
        return math.exp(log_I)
    t = duration_min
    if formula == 'general':
        return params['a'] / (t ** params['n'] + params['b'])
    elif formula == 'talbot':
        return params['a'] / (t + params['b'])
    elif formula == 'sherman':
        return params['a'] / (t ** params['b'])
    elif formula == 'japanese':
        return params['a'] / (math.sqrt(t) + params['b'])
    else:
        raise ValueError(f"지원하지 않는 강우강도식: {formula}")


def calc_rainfall(formula: str, params: dict, duration_min: float) -> float:
    return round(calc_intensity(formula, params, duration_min) * duration_min / 60.0, 2)


def calc_rainfall_series(formula: str, params: dict, durations: list) -> dict:
    return {d: calc_rainfall(formula, params, d) for d in durations}


# ============================================================
# 2. 티센 가중 평균
# ============================================================

def calc_thiessen_rainfall(stations: list) -> float:
    """
    stations: [{'name':str, 'rainfall_mm':float, 'thiessen_area_km2':float}, ...]
    """
    total_area = sum(s['thiessen_area_km2'] for s in stations)
    if total_area <= 0:
        raise ValueError("티센 면적 합이 0 이하입니다.")
    weighted = sum(s['rainfall_mm'] * s['thiessen_area_km2'] for s in stations)
    return round(weighted / total_area, 2)


def calc_thiessen_rainfall_series(stations_by_duration: dict) -> dict:
    return {dur: calc_thiessen_rainfall(st)
            for dur, st in stations_by_duration.items()}


