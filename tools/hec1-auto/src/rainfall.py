# 6. 통합 처리 함수 (하위 호환용 — formula/thiessen 모드)
# ============================================================

def prepare_rainfall(
    stations: list,
    duration_min: int,
    return_period: int,
    basin_area_km2: float,
    cluster: int,
    quartile: int = 3,
    arf_region: str = '한강',
    dt_min: int = 10,
) -> dict:
    """
    표준지침 절차 전체: 티센가중 → ARF → Huff분포

    Parameters
    ----------
    stations       : [{'name':str, 'rainfall_mm':float, 'thiessen_area_km2':float}...]
    duration_min   : 지속기간 (분)
    return_period  : 재현기간 (년)
    basin_area_km2 : 유역면적 (km²)
    cluster        : 군집지역 번호 (1~26)
    quartile       : Huff 분위 (기본 3)
    arf_region     : 유역 본류 권역 ('한강'|'낙동강'|'금강'|'영산강')
    dt_min         : 시간간격 (분)

    Returns
    -------
    dict:
      point_rainfall  : 티센 가중 지점확률강우량 (mm)
      arf             : 면적우량환산계수
      areal_rainfall  : 면적확률강우량 (mm) → HEC-1 PB카드
      huff_ratios     : 누가강우비 배열 → HEC-1 PC카드
    """
    point_rf = calc_thiessen_rainfall(stations)
    arf      = calc_arf(basin_area_km2, duration_min, return_period, arf_region)
    areal_rf = round(point_rf * arf, 2)
    ratios   = calc_huff_distribution(areal_rf, duration_min,
                                       cluster, quartile, dt_min)
    return {
        'point_rainfall': point_rf,
        'arf':            arf,
        'areal_rainfall': areal_rf,
        'huff_ratios':    ratios,
    }


def prepare_rainfall_from_formula(
    formula: str,
    params: dict,
    duration_min: int,
    return_period: int,
    basin_area_km2: float,
    cluster: int,
    quartile: int = 3,
    arf_region: str = '한강',
    dt_min: int = 10,
) -> dict:
    """
    강우강도식으로 확률강우량 직접 계산 후 ARF → Huff 분포.
    단일 관측소 또는 이미 가중평균된 계수를 사용하는 경우.
    """
    point_rf = calc_rainfall(formula, params, duration_min)
    arf      = calc_arf(basin_area_km2, duration_min, return_period, arf_region)
    areal_rf = round(point_rf * arf, 2)
    ratios   = calc_huff_distribution(areal_rf, duration_min,
                                       cluster, quartile, dt_min)
    return {
        'point_rainfall': point_rf,
        'arf':            arf,
        'areal_rainfall': areal_rf,
        'huff_ratios':    ratios,
    }
