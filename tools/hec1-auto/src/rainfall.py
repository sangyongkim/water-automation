# 5. 관측소별 가중 Huff 누가분포
# ============================================================

def calc_weighted_huff_distribution(
    station_weights: list,
    stations: dict,
    duration_min: int,
    quartile: int = 3,
    dt_min: int = 10,
) -> list:
    """
    관측소별 티센 가중치와 군집번호를 적용한 Huff 누가분포 계산.

    Parameters
    ----------
    station_weights : [(관측소명, 가중치), ...]
    stations        : STATIONS dict (관측소명 → {'huff_cluster': int, ...})
    duration_min    : 지속기간 (분)
    quartile        : Huff 분위 (기본 3)
    dt_min          : 시간간격 (분)

    Returns
    -------
    list[float] : 가중 평균 누가강우비 (0→1), n_steps+1 개
    """
    n_steps = duration_min // dt_min
    result  = [0.0] * (n_steps + 1)
    total_w = 0.0

    for stn_name, weight in station_weights:
        if weight == 0.0:
            continue
        stn_cfg = stations.get(stn_name)
        if stn_cfg is None:          # DUMMY
            continue
        cluster = stn_cfg.get('huff_cluster')
        if cluster is None:
            raise ValueError(
                f"STATIONS['{stn_name}']에 huff_cluster가 정의되지 않았습니다."
            )
        ratios = calc_huff_distribution(100.0, duration_min, cluster, quartile, dt_min)
        for i, r in enumerate(ratios):
            result[i] += weight * r
        total_w += weight

    if total_w <= 0:
        raise ValueError("유효한 가중치가 없습니다 (모든 가중치가 0이거나 DUMMY).")

    if abs(total_w - 1.0) > 0.001:
        result = [r / total_w for r in result]

    # 단조증가 보정
    for i in range(1, len(result)):
        if result[i] < result[i - 1]:
            result[i] = result[i - 1]
    result[0]  = 0.0
    result[-1] = 1.0
    return [round(r, 4) for r in result]


