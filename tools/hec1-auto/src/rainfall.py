_ARF_DUR_HR = [1, 2, 3, 4, 6, 9, 12, 15, 18, 24, 48, 72]


def calc_arf(area_km2: float, duration_min: int,
             return_period: int, region: str = '한강') -> float:
    """
    면적우량환산계수(ARF) 계산.
    유역면적 25.9 km² 이하 → 1.0 반환.
    region: 유역 본류에 따라 '한강'|'낙동강'|'금강'|'영산강' 지정
    """
    if area_km2 <= 25.9:
        return 1.0
    rp_params = ARF_PARAMS.get(region)
    if rp_params is None:
        raise ValueError(f"지원하지 않는 ARF 권역: {region}. "
                         f"사용 가능: {list(ARF_PARAMS.keys())}")
    available = sorted(rp_params.keys())
    rp_use    = min(available, key=lambda x: abs(x - return_period))
    if rp_use != return_period and region != '한강':
        warnings.warn(
            f"[ARF] '{region}' 권역은 {return_period}년 계수가 없어 "
            f"{rp_use}년 계수로 대체합니다. (사용 가능: {available})",
            UserWarning, stacklevel=3
        )
    dur_hr    = duration_min / 60.0
    closest   = min(_ARF_DUR_HR, key=lambda x: abs(x - dur_hr))
    M, a, b   = rp_params[rp_use][closest]
    arf = 1.0 - M * math.exp(-1.0 / (a * (area_km2 ** b)))
    return round(min(max(arf, 0.0), 1.0), 4)


def apply_arf(rainfall_mm: float, area_km2: float,
              duration_min: int, return_period: int,
              region: str = '한강') -> float:
    return round(rainfall_mm * calc_arf(area_km2, duration_min, return_period, region), 2)


