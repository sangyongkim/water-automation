def calc_huff_ratio(t_ratio: float, cluster: int, quartile: int = 3) -> float:
    """
    수정 Huff 6차 다항식으로 무차원 누가강우비(0~1) 계산.
    t_ratio: 0~1 (무차원 경과시간비)
    quartile: 1~4 (기본 3 - 지침 채택)
    """
    if cluster not in HUFF_COEFFICIENTS:
        raise ValueError(
            f"군집 {cluster}의 Huff 계수가 없습니다.\n"
            f"사용 가능: {sorted(HUFF_COEFFICIENTS.keys())}"
        )
    a, b, c, d, e, f, g = HUFF_COEFFICIENTS[cluster][quartile]
    t   = t_ratio * 100.0   # 내부 계산 단위: 0~100
    pct = a*t**6 + b*t**5 + c*t**4 + d*t**3 + e*t**2 + f*t + g
    return round(min(max(pct / 100.0, 0.0), 1.0), 4)


def calc_huff_distribution(total_rainfall_mm: float,
                            duration_min: int,
                            cluster: int,
                            quartile: int = 3,
                            time_interval_min: int = 10) -> list:
    """
    수정 Huff 분위법으로 HEC-1 PC카드용 누가강우비 배열 계산.
    지침 채택: 3분위 50% 누가곡선 → quartile=3 고정 권장.

    Returns: list[float], 각 시각의 누가강우비 (0.0~1.0), n_steps+1 개
    """
    n_steps = duration_min // time_interval_min
    ratios  = [calc_huff_ratio(step / n_steps, cluster, quartile)
               for step in range(n_steps + 1)]
    # 단조증가 보정 (6차 다항식 진동 방지)
    for i in range(1, len(ratios)):
        if ratios[i] < ratios[i - 1]:
            ratios[i] = ratios[i - 1]
    ratios[0]  = 0.0
    ratios[-1] = 1.0
    return [round(r, 4) for r in ratios]


